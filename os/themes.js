// Build a CSS variables object from a flavor+mode for inline style consumption.
window.osTheme = function osTheme(flavorKey, mode) {
  const flavor = window.OS_FLAVORS[flavorKey] || window.OS_FLAVORS.phosphor;
  const t = flavor[mode] || flavor.dark;
  return {
    "--bg": t.bg,
    "--bg-inset": t.bgInset,
    "--surface": t.surface,
    "--surface-alt": t.surfaceAlt,
    "--border": t.border,
    "--border-bright": t.borderBright,
    "--fg": t.fg,
    "--fg-dim": t.fgDim,
    "--fg-mute": t.fgMute,
    "--accent": t.accent,
    "--accent-glow": t.accentGlow,
    "--danger": t.danger,
    "--warn": t.warn,
    "--info": t.info,
    "--sel-bg": t.selBg,
    "--sel-fg": t.selFg,
    "--shadow": t.shadow,
    "--scanline-opacity": t.scanlineOpacity,
    "--text-glow": t.glowText ? `0 0 6px ${t.accentGlow}` : "none",
    "--font-mono": "'JetBrains Mono', 'Fira Code', 'Menlo', 'Consolas', 'Courier New', monospace",
    color: t.fg,
    background: t.bg,
    fontFamily: "'JetBrains Mono', 'Fira Code', 'Menlo', 'Consolas', 'Courier New', monospace",
  };
};
